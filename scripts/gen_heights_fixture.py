#!/usr/bin/env python3
"""Generate src/fixtures/heights.ts (the bundled block-count snapshot).

Usage:  python3 -I scripts/gen_heights_fixture.py <heights_daily.csv> <out.ts>
        e.g. ... heights_daily.csv src/fixtures/heights.ts

INPUT CSV (header `date,blkcnt,cum_blocks`), one row per UTC day from 2009-01-03 with no
gaps: `blkcnt` is Coin Metrics' community-API `BlkCnt` metric (blocks per day, asset btc,
frequency 1d; https://community-api.coinmetrics.io/v4/timeseries/asset-metrics), and
`cum_blocks` the running sum of `blkcnt` (a cross-check column: the script verifies it).
The CSV is not stored in the repo; re-fetch the series (the most recent day may be
partial, so stop at the last complete UTC day) and update FETCHED below.

The output stores only the daily counts (compact); heights are rebuilt at import time.
It also embeds the measured Coin Metrics-to-chain offset (5) and its provenance, which
are measurements, not outputs of this script: re-measure them with the three
mempool.space lookups described in the header before regenerating from newer data.
"""
import csv, datetime, sys

if len(sys.argv) != 3:
    sys.exit(__doc__)
CSV, OUT = sys.argv[1], sys.argv[2]
FETCHED = '2026-11-27'

rows = list(csv.DictReader(open(CSV)))
counts, cum, prev = [], 0, None
for r in rows:
    d = datetime.date.fromisoformat(r['date'])
    if prev is not None:
        assert d == prev + datetime.timedelta(days=1), ('gap', r['date'])
    prev = d
    c = int(r['blkcnt'])
    cum += c
    assert cum == int(r['cum_blocks']), ('cum mismatch', r['date'], cum, r['cum_blocks'])
    counts.append(c)
cumtrue = cum - 5
first, last = rows[0]['date'], rows[-1]['date']
assert first == '2009-01-03'

lines = []
per = 24
for i in range(0, len(counts), per):
    lines.append('  ' + ', '.join(str(c) for c in counts[i:i + per]) + ',')

src = f"""/**
 * Real daily Bitcoin block counts, 2009-01-03 -> {last}, plus helpers that rebuild
 * the cumulative height series from them.
 *
 * SOURCE : Coin Metrics community API, metric `BlkCnt` (blocks per UTC day), asset btc,
 *          frequency 1d. https://community-api.coinmetrics.io/v4/timeseries/asset-metrics
 * FETCHED: {FETCHED} (last full UTC day in the snapshot: {last}; {len(counts)} days).
 * GENERATED by scripts/gen_heights_fixture.py from a heights_daily.csv (date,blkcnt,cum_blocks)
 *          (the generator checked the days are contiguous and that the running sum
 *          reproduces the file's cum_blocks column). Do not edit by hand.
 *
 * DEFINITION OF h: `h(D)` = TRUE chain height of the last block mined on UTC day D
 * (genesis = height 0). The daily counts below are Coin Metrics' raw `BlkCnt`
 * (genesis not counted, so their running sum is the chain height PLUS a small
 * offset); `heightsFromSnapshot()` returns running sum - SNAPSHOT_HEIGHT_OFFSET
 * (floored at 0), i.e. true heights. `blockCountsFromSnapshot()` returns the raw
 * counts unchanged. Running sum at {last} = {cum}; true h = {cumtrue}.
 *
 * OFFSET MEASUREMENT (2026-11-27): three immutable mempool.space lookups
 * (/api/v1/mining/blocks/timestamp/<unix>) of the last block before 00:00Z gave
 *   before 2026-11-20 -> height 976,656   (Coin Metrics running sum 2026-11-19 = 976,661)
 *   before 2026-11-26 -> height 977,595   (running sum 2026-11-25 = 977,600)
 *   before 2026-11-27 -> height 977,730   (running sum 2026-11-26 = 977,735)
 * so running sum = chain height + 5 on all three. The app re-measures this on every
 * reconcile and only falls back to this constant when it has never calibrated.
 * Day-boundary attribution follows Coin Metrics (block header time).
 *
 * Roles: production last-resort seed (no network, store short), MOCK=1 backing data,
 * and test fixture. DATA ONLY: no model coefficient lives here.
 */

import type {{ BlockCountObservation, HeightObservation }} from '../types.js';

/** ISO date this snapshot was fetched (see header). */
export const HEIGHTS_FETCHED_AT = '{FETCHED}' as const;

/**
 * Measured `Coin Metrics running sum - chain height` (blocks) on 2026-11-27, from
 * three mempool.space lookups (see header). DATA constant, not a fitted coefficient;
 * the live app recalibrates it and uses this only when it has never succeeded.
 */
export const SNAPSHOT_HEIGHT_OFFSET = 5;

/** First day of the series (the genesis block's UTC day). */
export const HEIGHTS_START_DATE = '{first}' as const;

/** Last full UTC day in the snapshot. */
export const HEIGHTS_SNAPSHOT_END = '{last}' as const;

/** Blocks mined on each UTC day from HEIGHTS_START_DATE (index 0 = 2009-01-03). */
export const DAILY_BLOCK_COUNTS: ReadonlyArray<number> = [
{chr(10).join(lines)}
];

function dateAt(index: number): string {{
  return new Date(Date.parse(`${{HEIGHTS_START_DATE}}T00:00:00Z`) + index * 86_400_000)
    .toISOString()
    .slice(0, 10);
}}

/** The snapshot as `{{date, count}}[]` (what a Coin Metrics `fetchBlockCounts` returns). */
export function blockCountsFromSnapshot(): BlockCountObservation[] {{
  return DAILY_BLOCK_COUNTS.map((count, i) => ({{ date: dateAt(i), count }}));
}}

/** The snapshot as TRUE-height `{{date, h}}[]`: running sum of counts minus SNAPSHOT_HEIGHT_OFFSET, floored at 0. */
export function heightsFromSnapshot(): HeightObservation[] {{
  const out: HeightObservation[] = [];
  let h = 0;
  for (let i = 0; i < DAILY_BLOCK_COUNTS.length; i++) {{
    h += DAILY_BLOCK_COUNTS[i] as number;
    out.push({{ date: dateAt(i), h: Math.max(0, h - SNAPSHOT_HEIGHT_OFFSET) }});
  }}
  return out;
}}
""".replace('{cum}', str(cum)).replace('{cumtrue}', str(cum-5))
open(OUT, 'w').write(src)
print('wrote', OUT, len(counts), 'days, last', last, 'cum', cum)
